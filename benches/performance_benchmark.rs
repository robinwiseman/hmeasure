use criterion::{criterion_group, criterion_main, BenchmarkId, Criterion};

use hmeasure::{BetaParams, BinaryClassParams, BinaryClassScores, BinaryClassifierScores};
use hmeasure::{CostDistribution, CostRatioDensity, HMeasure};

fn hmeasure_benchmark(cr: &mut Criterion) {
    let base = 100;
    let mut group = cr.benchmark_group("hmeasure_benchmark");
    for size in [
        base,
        2 * base,
        4 * base,
        8 * base,
        16 * base,
        32 * base,
        64 * base,
        128 * base,
        256 * base,
    ]
    .iter()
    {
        // Data generation stays outside the timed closure.
        let scores = generate_scores(*size);
        group.bench_with_input(BenchmarkId::from_parameter(size), size, |b, _| {
            b.iter(|| h_measure(beta_2_2(), &scores));
        });
    }
    group.finish();
}

fn generate_scores(size: usize) -> BinaryClassScores {
    /* Choose beta parameters for the model scores distributions that illustrate
    the case of a model that is able to reasonably discriminate between the two classes
    => the score distributions generated by the model are fairly distinct, albeit not
     completely partitioned.*/
    let class0_params = BetaParams {
        alpha: 2.0,
        beta: 6.0,
    };
    let class1_params = BetaParams {
        alpha: 6.0,
        beta: 2.0,
    };
    let bcp = BinaryClassParams {
        class0: class0_params,
        class1: class1_params,
    };
    // seed the random number generator for reproducibility.
    let mut rng = BinaryClassifierScores::generate_rng(13);
    BinaryClassifierScores::new(&bcp, size, size, &mut rng)
        .unwrap()
        .scores
}

fn h_measure<C: CostDistribution>(cost_distribution: C, scores: &BinaryClassScores) -> f64 {
    HMeasure::new(cost_distribution, None, None)
        .unwrap()
        .h_measure(scores)
        .unwrap()
        .h
}

fn beta_2_2() -> CostRatioDensity {
    CostRatioDensity::new(BetaParams {
        alpha: 2.0,
        beta: 2.0,
    })
    .unwrap()
}

struct BetaByQuadrature(CostRatioDensity);

impl CostDistribution for BetaByQuadrature {
    fn pdf(&self, cost: f64) -> f64 {
        self.0.pdf(cost)
    }
}

// The same Beta(2, 2) cost density evaluated in closed form and by the default numerical quadrature.
fn cost_distribution_benchmark(cr: &mut Criterion) {
    let scores = generate_scores(1600);
    let mut group = cr.benchmark_group("cost_distribution");
    group.bench_function("beta_closed_form", |b| {
        b.iter(|| h_measure(beta_2_2(), &scores));
    });
    group.bench_function("beta_quadrature", |b| {
        b.iter(|| h_measure(BetaByQuadrature(beta_2_2()), &scores));
    });
    group.finish();
}

criterion_group!(benches, hmeasure_benchmark, cost_distribution_benchmark);
criterion_main!(benches);
