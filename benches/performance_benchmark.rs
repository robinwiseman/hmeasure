use criterion::{criterion_group, criterion_main, BatchSize, BenchmarkId, Criterion};

use hmeasure::{BetaParams, BinaryClassParams, BinaryClassScores, BinaryClassifierScores};
use hmeasure::{CostRatioDensity, HMeasure};

fn hmeasure_benchmark(cr: &mut Criterion) {
    let base = 100;
    let mut group = cr.benchmark_group("hmeasure_benchmark");
    for size in [
        base,
        2 * base,
        4 * base,
        8 * base,
        16 * base,
        32 * base,
        64 * base,
        128 * base,
        256 * base,
    ]
    .iter()
    {
        let (class0, class1) = generate_scores(*size);
        group.bench_with_input(BenchmarkId::from_parameter(size), size, |b, _| {
            // h_measure sorts the scores in place, so each iteration gets a fresh unsorted copy,
            // built in the untimed setup closure.
            b.iter_batched(
                || {
                    let crd = CostRatioDensity::new(BetaParams {
                        alpha: 2.0,
                        beta: 2.0,
                    });
                    let scores = BinaryClassScores {
                        class0: class0.clone(),
                        class1: class1.clone(),
                    };
                    (HMeasure::new(crd, None, None), scores)
                },
                |(mut hm, mut scores)| hm.h_measure(&mut scores).h,
                BatchSize::LargeInput,
            );
        });
    }
    group.finish();
}

fn generate_scores(size: usize) -> (Vec<f64>, Vec<f64>) {
    /* Choose beta parameters for the model scores distributions that illustrate
    the case of a model that is able to reasonably discriminate between the two classes
    => the score distributions generated by the model are fairly distinct, albeit not
     completely partitioned.*/
    let class0_params = BetaParams {
        alpha: 2.0,
        beta: 6.0,
    };
    let class1_params = BetaParams {
        alpha: 6.0,
        beta: 2.0,
    };
    let bcp = BinaryClassParams {
        class0: class0_params,
        class1: class1_params,
    };
    // seed the random number generator for reproducibility.
    let mut rng = BinaryClassifierScores::generate_rng(13);
    let bcs = BinaryClassifierScores::new(&bcp, size, size, &mut rng);
    (bcs.scores.class0, bcs.scores.class1)
}

criterion_group!(benches, hmeasure_benchmark);
criterion_main!(benches);
